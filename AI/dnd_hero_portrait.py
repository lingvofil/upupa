"""Hero portrait for the «Герой» card: drawn once, kept with the hero, redrawn on request.

The portrait belongs to a concrete hero, not to a campaign: it is stored next to
the hero's progression in the campaign archive and comes back in the next party
while the character profile stays the same. A different profile is a different
hero and gets a fresh portrait.

Telegram only accepts a photo upload once; afterwards the card reuses the
``file_id``. Freshly generated bytes wait in memory until the hero card shows
them (a restart before that just means the hero is drawn again).
"""
from __future__ import annotations

import asyncio
import copy
import hashlib
import json
import logging
import time

PORTRAIT_FIELD = "hero_portraits"
REGEN_COOLDOWN_SECONDS = 180
GENERATION_TIMEOUT_SECONDS = 150
CAPTION_LIMIT = 1024

ARCHETYPE_LOOK = {
    "сила": "broad-shouldered bruiser, heavy build, battle-worn gear",
    "ловкость": "lean agile rogue, light practical gear, quick confident stance",
    "разум": "sharp-eyed scholar-tinkerer, pockets of notes and odd tools",
    "мудрость": "calm healer-wanderer, herbs and charms, attentive gaze",
    "харизма": "flamboyant smooth talker, eye-catching outfit, theatrical smile",
    "стойкость": "unshakeable survivor, patched armor, scars worn with pride",
}
_GENDER_WORD = {"мужской": "a man", "женский": "a woman"}

# chat_id, user_id -> generated bytes waiting for their first upload
_pending: dict[tuple[int, int], tuple[bytes, str]] = {}
_inflight: set[tuple[int, int]] = set()


def _key(session, user_id) -> tuple[int, int]:
    return int(getattr(session, "chat_id", 0) or 0), int(user_id)


def ensure(session) -> None:
    if not isinstance(getattr(session, PORTRAIT_FIELD, None), dict):
        setattr(session, PORTRAIT_FIELD, {})


def profile_signature(profile) -> str:
    """Identity of a hero for portrait purposes; stats and progress don't count."""
    profile = profile if isinstance(profile, dict) else {}
    core = {key: profile.get(key) for key in ("gender", "style", "strength", "weakness", "special") if profile.get(key)}
    return hashlib.sha1(json.dumps(core, ensure_ascii=False, sort_keys=True).encode("utf-8")).hexdigest()[:16]


def _profile(session, user_id) -> dict:
    row = (getattr(session, "character_profiles", {}) or {}).get(str(int(user_id)))
    return row if isinstance(row, dict) else {}


def can_draw(session, user_id) -> bool:
    """A portrait needs at least an appearance to draw from."""
    return bool(_profile(session, user_id).get("style"))


def _archived(session, user_id, signature) -> dict | None:
    try:
        from AI import dnd_campaign as campaign

        history = campaign._player_history(session.chat_id, int(user_id)) or {}
    except Exception:
        return None
    row = history.get("portrait") if isinstance(history, dict) else None
    if isinstance(row, dict) and row.get("file_id") and row.get("sig") == signature:
        return {"file_id": str(row["file_id"]), "sig": signature, "version": int(row.get("version") or 1),
                "created_at": float(row.get("created_at") or 0)}
    return None


def portrait_record(session, user_id) -> dict | None:
    """The current hero's stored portrait, pulling it from the archive once."""
    ensure(session)
    key = str(int(user_id))
    signature = profile_signature(_profile(session, user_id))
    row = session.hero_portraits.get(key)
    if isinstance(row, dict) and row.get("sig") == signature and row.get("file_id"):
        return row
    archived = _archived(session, user_id, signature)
    if archived:
        session.hero_portraits[key] = archived
        return archived
    return None


def photo_for(session, user_id):
    """What the hero card should show: fresh bytes to upload, a file_id, or None."""
    pending = _pending.get(_key(session, user_id))
    if pending and pending[1] == profile_signature(_profile(session, user_id)):
        from aiogram.types import BufferedInputFile

        return BufferedInputFile(pending[0], filename="dnd_hero_portrait.png")
    row = portrait_record(session, user_id)
    return row["file_id"] if row else None


def remember_upload(session, user_id, message) -> None:
    """Store the Telegram file_id of an uploaded portrait and drop the bytes."""
    photos = getattr(message, "photo", None) or []
    file_id = getattr(photos[-1], "file_id", None) if photos else None
    pending = _pending.pop(_key(session, user_id), None)
    if not file_id:
        return
    ensure(session)
    key = str(int(user_id))
    previous = session.hero_portraits.get(key) if isinstance(session.hero_portraits.get(key), dict) else {}
    session.hero_portraits[key] = {
        "file_id": str(file_id),
        "sig": pending[1] if pending else profile_signature(_profile(session, user_id)),
        "version": int(previous.get("version") or 0) + 1,
        "created_at": time.time(),
    }
    for field in ("requested_at", "requested_sig"):
        # The redraw cooldown counts from the request, not from the upload.
        if previous.get(field):
            session.hero_portraits[key][field] = previous[field]


def is_generating(session, user_id) -> bool:
    return _key(session, user_id) in _inflight


def cooldown_left(session, user_id) -> int:
    row = (getattr(session, PORTRAIT_FIELD, None) or {}).get(str(int(user_id))) or {}
    last = float(row.get("requested_at") or 0)
    return max(0, int(last + REGEN_COOLDOWN_SECONDS - time.time()))


def _artifacts(session, user_id, limit=2) -> list[str]:
    names = []
    for item in (getattr(session, "inventories", {}) or {}).get(str(int(user_id))) or []:
        if isinstance(item, dict) and item.get("kind") == "artifact" and item.get("name"):
            names.append(str(item["name"])[:60])
    return names[:limit]


def build_portrait_prompt(session, user_id) -> str:
    """Appearance-only prompt; no names, so the model has nothing to letter."""
    from AI.dnd_archetype_abilities import archetype_of
    from AI.dnd_progression import LEVEL_TITLES, level_of

    profile = _profile(session, user_id)
    who = _GENDER_WORD.get(str(profile.get("gender") or "").casefold(), "a person")
    archetype = archetype_of(session, user_id)
    level = level_of(session, user_id)
    lines = [
        "Create ONE character portrait of a single tabletop-RPG hero from an absurd comedic adventure.",
        "Waist-up, facing the viewer, expressive face, clear silhouette, simple atmospheric background.",
        "Exactly one person. ABSOLUTELY NO text, letters, names, captions, frames, UI, cards or watermarks.",
        "VISUAL STYLE: vivid painted fantasy character portrait, rich color, dramatic rim light.",
        f"WHO: {who}.",
        f"APPEARANCE AND IMAGE (most important): {str(profile.get('style') or '')[:300]}.",
    ]
    if archetype in ARCHETYPE_LOOK:
        lines.append(f"ROLE LOOK: {ARCHETYPE_LOOK[archetype]}.")
    if profile.get("strength"):
        lines.append(f"Hint of their strength in the pose or props: {str(profile['strength'])[:150]}.")
    artifacts = _artifacts(session, user_id)
    if artifacts:
        lines.append("Carries or wears, if it can be shown as an object: " + "; ".join(artifacts) + ".")
    if level >= 5:
        lines.append(f"Seasoned veteran ({LEVEL_TITLES.get(level, '')}): confident, gear shows many adventures.")
    return "\n".join(lines)


def begin(session, user_id) -> bool:
    """Mark a drawing as started (synchronously, so the card can say so at once)."""
    key = _key(session, user_id)
    if key in _inflight:
        return False
    ensure(session)
    row = session.hero_portraits.setdefault(str(int(user_id)), {})
    row["requested_at"] = time.time()
    row["requested_sig"] = profile_signature(_profile(session, user_id))
    _inflight.add(key)
    return True


def auto_attempted(session, user_id) -> bool:
    """Whether this very hero already had an automatic attempt (success or not)."""
    row = (getattr(session, PORTRAIT_FIELD, None) or {}).get(str(int(user_id))) or {}
    return row.get("requested_sig") == profile_signature(_profile(session, user_id))


async def generate(session, user_id) -> bool:
    """Draw a portrait started with ``begin``; returns True when bytes are ready."""
    from AI.dnd_image_quality import generate_dnd_image_bytes

    key = _key(session, user_id)
    if key not in _inflight and not begin(session, user_id):
        return False
    signature = profile_signature(_profile(session, user_id))
    try:
        prompt = build_portrait_prompt(session, user_id)
        data, provider = await asyncio.wait_for(generate_dnd_image_bytes(prompt), timeout=GENERATION_TIMEOUT_SECONDS)
        if not data:
            logging.warning("[dnd] hero portrait: all providers failed chat_id=%s user=%s", key[0], key[1])
            return False
        if profile_signature(_profile(session, user_id)) != signature:
            logging.info("[dnd] hero portrait dropped: hero changed chat_id=%s user=%s", key[0], key[1])
            return False
        _pending[key] = (bytes(data), signature)
        logging.info("[dnd] hero portrait ready provider=%s chat_id=%s user=%s", provider, key[0], key[1])
        return True
    except Exception:
        logging.exception("[dnd] hero portrait generation failed chat_id=%s user=%s", key[0], key[1])
        return False
    finally:
        _inflight.discard(key)


def archive_portraits(session, players: dict) -> None:
    """Keep each living hero's portrait in the cross-campaign player history."""
    for key, row in (getattr(session, PORTRAIT_FIELD, None) or {}).items():
        history = players.get(str(key))
        if isinstance(row, dict) and row.get("file_id") and isinstance(history, dict):
            history["portrait"] = {k: copy.deepcopy(row[k]) for k in ("file_id", "sig", "version", "created_at") if k in row}


def caption(text: str) -> str:
    text = str(text or "")
    return text if len(text) <= CAPTION_LIMIT else text[:CAPTION_LIMIT - 1].rstrip() + "…"


def install_dnd_hero_portrait(*, state_policy) -> None:
    from AI import dnd_progression as progression

    state_policy.add_ensure_hook(ensure)
    state_policy.add_state_field(PORTRAIT_FIELD, lambda s: {
        key: {k: v for k, v in row.items() if k not in {"requested_at", "requested_sig"}}
        for key, row in (getattr(s, PORTRAIT_FIELD, None) or {}).items() if isinstance(row, dict)
    })
    state_policy.add_restore_hook(lambda session, _data=None: ensure(session))
    progression.register_archive_hook(archive_portraits)


