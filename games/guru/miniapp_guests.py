"""Bonus guests based on recurring exchanges and speech in the Telegram export."""
from dataclasses import dataclass

from games.guru.model import Question, Story
from games.guru.seance_natal import Aspect, Reading


@dataclass(frozen=True)
class ChatGuest:
    tale: Story
    sign: str | None
    palm: str
    greeting: str
    postscript: str
    return_scene: str
    chart: tuple[str, tuple[Aspect, Aspect]]
    voice: dict[str, str]
    word: str = ""
    intro_observations: tuple[str, ...] = ()
    observations: tuple[str, ...] = ()


def reactions(tarot, palm, horoscope, vague, suspicious, final, happy, *, admit, ask):
    return {
        "open.tarot": tarot, "open.palm": palm, "open.horoscope": horoscope,
        "hollow": vague, "dark.firm": suspicious, "final": final, "outcome.content": happy,
        "outcome.mixed": final, "outcome.displeased": vague, "followup.admit": admit, "followup.ask": ask,
    }


def guest(key, name, sign, archetype, arrival, told, questions, claim, truth, reveal, palm, postscript, aspects,
          *, greeting, return_scene, voice, word="", intro_observations=(), observations=()):
    who, what = truth
    claim_who, claim_what = claim
    decoys = tuple(dict.fromkeys((claim_who, "friend", "self", "colleague", "newbie")))
    questions = tuple(Question(f"detail{i}", label, answer, "check" if i < 2 else "open")
                      for i, (label, answer) in enumerate(questions))
    tale = Story(
        id=f"chat.{key}", archetype=archetype, names=(name,), arrival=arrival, told=told,
        said={"who": claim_who, "what": claim_what}, points=(), questions=questions,
        who=who, what=what, when_options=("today", "week"), who_decoys=tuple(tag for tag in decoys if tag != who)[:3],
        reveal=reveal, fee=2700,
    )
    readings = [Reading(q.label, q.answer, observations[i] if observations else "") for i, q in enumerate(questions)]
    chart = tuple(Aspect(planet, house, tension, note, readings[i], readings[i + 2])
                  for i, (planet, house, tension, note) in enumerate(aspects))
    return ChatGuest(tale, sign, palm, greeting, postscript, return_scene, ("sun" if sign else "mercury", chart),
                     voice, word, intro_observations, observations)


