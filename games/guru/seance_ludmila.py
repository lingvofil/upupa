META: dict[str, ReadingData] = {reading.id: reading for card in CARDS for symbol in card.symbols for reading in symbol.readings}
ORDER = ("trusts", "wavers", "suspects", "convinced")
EVENT_OF_INTENT = {"accuse": "accuse", "call": "reveal", "sing": "reserve"}


@dataclass
class World:
    belief: str = "suspects"  # что она думает о муже: trusts | wavers | suspects | convinced
    expectation: str = "open"  # чего ждёт от праздника: open | low | modest | gift | luxury
    intents: dict[str, str] = field(default_factory=dict)  # что задумала, но не сделала: замысел → утверждение
    tempered: dict[str, bool] = field(default_factory=lambda: {"impulse": False, "bias": False, "festive": False, "restless": False})
    flags: dict[str, bool] = field(default_factory=lambda: {"mends": False, "yield_stage": False, "reminded": False})
    credibility: str = "intact"  # верит ли гадалке на слово: intact | shaken
    hollow: int = 0  # сколько гаданий оставили её без ответа
    gift_hints: int = 0
    used: dict[str, int] = field(default_factory=dict)  # счётчики вариантов реплик


def _calm(w: World, to: str) -> None:
    if ORDER.index(w.belief) > ORDER.index(to):
        w.belief = to


def _alarm(w: World, to: str) -> None:
    if ORDER.index(w.belief) < ORDER.index(to):
        w.belief = to


def _suspicious(w: World) -> bool:
    return w.belief in ("suspects", "convinced")


def _say(s: State, key: str) -> None:
    variants = LINES[key]
    n = s.world.used.get(key, 0)
    s.world.used[key] = n + 1
    push(s, "client", NAME, variants[n % len(variants)])


def _say_text(s: State, text: str) -> None:
    push(s, "client", NAME, text)


def _note(st: Statement, text: str) -> None:
    st.understood = f"{st.understood} {text}" if st.understood else text


def _standing(s: State, polarity: str, skip: Statement) -> Statement | None:
    """Утверждение противоположного смысла, которое гадалка не забрала назад."""
    return next((st for st in s.statements if st is not skip and st.data.get("polarity") == polarity and st.alive), None)


def _drop_intent(s: State, kind: str, state: str = "dropped") -> None:
    source = statement_of(s, s.world.intents.get(kind))
    if source is not None and source.intent == kind and source.intent_state == "open":
        source.intent_state = state
    s.world.intents.pop(kind, None)


def _set_intent(s: State, st: Statement, kind: str) -> None:
    if kind == "accuse":
        _drop_intent(s, "call")
    if kind == "call":
        _drop_intent(s, "accuse")
    _drop_intent(s, kind)
    s.world.intents[kind] = st.id
    st.intent, st.intent_state = kind, "open"


