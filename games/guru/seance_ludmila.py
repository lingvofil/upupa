def _hollow_said(s: State, st: Statement, key: str | None = None) -> None:
    w: World = s.world
    w.hollow += 1
    st.data["topic"] = "hollow"
    st.understood = "Ничего определённого не услышала."
    if has_event(s, "accuse"):
        _say(s, "hollow.afterAccuse")
        s.mood = "worried"
        return
    if has_event(s, "reveal"):
        _say(s, "hollow.afterReveal")
        s.mood = "thoughtful"
        return
    if not w.tempered["bias"]:
        if "accuse" in w.intents:
            _say(s, "hollow.bias.intent")
            w.belief = "convinced"
            st.misheard = True
            st.understood = "Приняла уклончивый ответ за подтверждение своих подозрений."
            if w.tempered["impulse"]:
                _say(s, "hollow.bias.tempered")
            else:
                _fire(s, "accuse", "bias", st)
            s.mood = "angry"
            return
        if w.hollow >= 2 and w.belief == "suspects":
            _say(s, "hollow.bias.second")
            w.belief = "convinced"
            st.misheard = True
            st.understood = "Решила: раз ей не говорят «нет», значит, «да»."
            s.mood = "angry"
            return
    _say(s, key or ("hollow.palm" if st.method == "palm" else f"hollow.{min(w.hollow, 3)}"))
    s.mood = "tired"


def _dark_said(s: State, st: Statement, echo: str | None) -> None:
    w: World = s.world
    firm = st.tone != E.SOFT
    st.data["polarity"], st.data["topic"] = "dark", "betrayal"
    if has_event(s, "reveal"):
        _say(s, "dark.afterReveal")
        w.credibility = "shaken"
        st.understood = "Гадалка спорит с тем, что муж уже объяснил."
        s.mood = "thoughtful"
        return
    if has_event(s, "accuse"):
        _say(s, "dark.afterAccuse")
        st.understood = "Гадалка подтверждает уже отправленное обвинение."
        s.mood = "angry"
        return
    earlier = _standing(s, "benign", st)
    if echo:
        _say_text(s, echo)
    if earlier is not None:
        _say(s, "contradiction.dark")
        w.credibility = "shaken"
        st.data["contradicts"] = earlier.id
    if firm:
        w.belief = "convinced"
        if w.tempered["impulse"]:
            _say(s, "dark.firm.tempered")
            _set_intent(s, st, "accuse")
            st.understood = "Измена подтверждена. Писать обещала не раньше утра."
        elif w.credibility == "shaken":
            _say(s, "dark.firm.shaken")
            _set_intent(s, st, "accuse")
            st.understood = "Гадалка уверена в измене, но на слово ей уже не верят."
        else:
            _say(s, "dark.firm")
            _fire(s, "accuse", "statement", st)
            st.understood = "Измена подтверждена. Можно обвинять."
    else:
        _alarm(w, "suspects")
        _say(s, "dark.soft")
        _set_intent(s, st, "accuse")
        st.misheard = True
        st.understood = "Даже гадалка допускает измену. Для неё это почти улика."
    s.mood = "angry"


def _kind_said(s: State, st: Statement, *, echo: str | None = None, fact: str | None = None, resonance: str | None = None,
               closure: bool = False, after_reveal: str | None = None, after_accuse: str | None = None) -> bool:
    """Доброе прочтение. ``False`` — оно опоздало, и разговор уже о другом."""
    w: World = s.world
    firm = st.tone == E.FIRM
    st.data["polarity"] = "benign"
    st.data.setdefault("topic", "kind")
    if has_event(s, "reveal"):
        _say(s, after_reveal or "kind.afterReveal")
        st.understood = "Это она уже знает от мужа."
        s.mood = "thoughtful"
        return False
    if has_event(s, "accuse"):
        _say(s, after_accuse or "kind.afterAccuse")
        _calm(w, "wavers")
        st.understood = "Доброе прочтение опоздало: обвинение уже отправлено."
        s.mood = "worried"
        return False
    earlier = _standing(s, "dark", st)
    if earlier is not None:
        _say(s, "contradiction.kind")
        w.credibility = "shaken"
        st.data["contradicts"] = earlier.id
        _calm(w, "wavers")
        if firm and "accuse" in w.intents:
            _drop_intent(s, "accuse")
            _say(s, "contradiction.kind.dropIntent")
        st.understood = "Гадалка противоречит самой себе: неясно, чему верить."
        s.mood = "worried"
        return True
    if echo:
        _say_text(s, echo)
    resonant = bool(fact) and fact in s.questions
    if resonant and resonance:
        _say_text(s, resonance)
    elif closure:
        _say(s, "kind.firm" if firm else "kind.soft")
    _calm(w, "trusts" if firm or resonant else "wavers")
    if w.belief == "trusts":
        _drop_intent(s, "accuse")
    st.data["resonant"] = resonant
    st.understood = ("Муж прячет что-то доброе. Подозрение почти ушло." if w.belief == "trusts"
                     else "Возможно, дело не в измене. Подозрение пошатнулось.")
    s.mood = "hopeful" if w.belief == "trusts" else "thoughtful"
    return True


def _promise(s: State, st: Statement, firm: bool) -> None:
    w: World = s.world
    st.data["topic"], st.data["risky"] = "grand", True
    if has_event(s, "reveal"):
        _say(s, "grand.afterReveal")
        _note(st, "Слова о роскоши не сходятся с тем, что она уже знает.")
    elif has_event(s, "accuse"):
        _say(s, "grand.afterAccuse")
        _note(st, "После обвинения ей не до подарков.")
    elif w.expectation == "luxury":
        # Сестра уже знает: второе обещание ничего не добавляет.
        _say(s, "grand.again")
        _note(st, "Обещание роскоши она слышит уже не в первый раз.")
    elif w.tempered["festive"]:
        _say(s, "grand.tempered")
        w.expectation = "gift"
        _note(st, "Подарок возможен, но салюта она обещала не ждать.")
    elif firm and w.credibility == "shaken":
        _say(s, "grand.shaken")
        w.gift_hints += 1
        w.expectation = "gift"
        _note(st, "Хочется верить в подарок, но гадалке она верит уже не на слово.")
    elif firm:
        _say(s, "grand.firm")
        _fire(s, "boast", "statement", st)
        _note(st, "Обещан дорогой подарок.")
    else:
        w.gift_hints += 1
        if w.gift_hints >= 2:
            _say(s, "grand.second")
            _fire(s, "boast", "hints", st)
            _note(st, "Второй намёк на подарок она приняла за обещание.")
            return
        _say(s, "grand.soft")
        w.expectation = "gift"
        _note(st, "Возможно что-то приятное; размер неизвестен.")
        s.mood = "hopeful"


def _stage(s: State, st: Statement, firm: bool) -> None:
    w: World = s.world
    st.data["topic"], st.data["risky"] = "stage", True
    grim = has_event(s, "accuse")
    if has_event(s, "reserve"):
        _say(s, "stage.again")
        st.understood = "Её выступление и так уже решено."
        return
    if w.flags["yield_stage"]:
        _say(s, "stage.yield")
        w.credibility = "shaken"
        _set_intent(s, st, "sing")
        st.understood = "Гадалка то сажает её в первый ряд, то зовёт на сцену."
        s.mood = "thoughtful"
        return
    if firm and not w.tempered["impulse"] and w.credibility == "intact":
        _say(s, "stage.firm.grim" if grim else "stage.firm.known" if has_event(s, "reveal") else "stage.firm")
        _fire(s, "reserve", "statement", st)
        st.understood = "Её место — у микрофона, а не в зале."
    else:
        _say(s, "stage.soft.grim" if grim else "stage.soft")
        _set_intent(s, st, "sing")
        st.understood = "Можно и самой выступить. Пока только мысль."
        if not grim:
            s.mood = "hopeful"


def _tarot(s: State, st: Statement) -> None:
    w: World = s.world
    lens, claim, coming = (META[part].meta for part in st.parts)
    firm = st.tone == E.FIRM
    if claim["claim"] == "dark" or coming["out"] == "break":
        _dark_said(s, st, claim.get("echo") if claim["claim"] == "dark" else coming.get("echo"))
        return
    mixed = lens["lens"] == "alarming"
    out = coming["out"]
    st.data["mixed"], st.data["out"] = mixed, out
    if mixed:
        # Сказано и тревожное, и доброе. Людмила выбирает то, чего боится.
        st.data["polarity"], st.data["topic"] = "benign", "kind"
        _say_text(s, lens["echo"])
        _say(s, "mixed.close")
        st.misheard = True
        st.understood = "Услышала только тревожную половину. Про доброе решила, что её утешают."
        s.mood = "worried"
    else:
        _kind_said(s, st, echo=claim.get("echo"), fact=claim.get("fact"), resonance=claim.get("resonance"), closure=out != "wait")
    if out == "wait":
        _say(s, "wait.mixed" if mixed else "wait.kind.firm" if firm else "wait.kind.soft")
    elif out == "ask":
        st.data["risky"] = True
        if firm and not w.tempered["impulse"] and w.credibility == "intact":
            _say(s, "ask.firm")
            _fire(s, "reveal", "statement", st)
            _note(st, "Выяснить всё можно одним звонком.")
        else:
            _say(s, "ask.held" if firm else "ask.soft")
            _set_intent(s, st, "call")
            _note(st, "Может быть, стоит спросить его прямо.")
    elif out == "grand":
        _promise(s, st, firm)
    elif out == "modest":
        if w.expectation == "luxury":
            _say(s, "modest.luxury")
        else:
            w.expectation = "modest"
            _say(s, "modest")
            _note(st, "Подарок будет простым, но своим.")
    elif out == "tender":
        _say(s, "tender")


def _palm(s: State, st: Statement) -> None:
    w: World = s.world
    acted = has_event(s, "accuse") or has_event(s, "reveal")
    st.data["topic"] = "self"
    part = st.parts[0]
    if part == "mars.temper":
        w.tempered["impulse"] = True
        if has_event(s, "accuse"):
            _say(s, "mars.temper.late")
            st.understood = "Совет не торопиться опоздал."
            s.mood = "worried"
        elif "accuse" in w.intents or "call" in w.intents:
            st.data["prevented"] = "accuse" if "accuse" in w.intents else "call"
