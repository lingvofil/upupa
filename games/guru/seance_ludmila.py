def stance_of(st: Statement) -> str:
    """Тип высказывания — для журнала и тестов; на последствия он сам не влияет."""
    if st.hollow or st.data.get("barnum"):
        return "evasive"
    if st.data.get("risky"):
        return "risky"
    return "cautious" if st.tone == E.SOFT else "firm"


