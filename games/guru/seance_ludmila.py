def _horoscope(s: State, st: Statement) -> None:
    w: World = s.world
    firm = st.tone == E.FIRM
    tone = "firm" if firm else "soft"
    part = st.parts[0]
    if part == "venus.confession":
        _kind_said(s, st, echo=LINES[f"confession.{tone}"][0], fact="sure", resonance=LINES["confession.resonance"][0])
    elif part == "venus.gift":
        _promise(s, st, firm)
    elif part == "mercury.shy":
        _kind_said(s, st, echo=LINES[f"shy.{tone}"][0], fact="sing", resonance=LINES["shy.resonance"][0])
    elif part == "mercury.early":
        st.data["topic"], st.data["risky"] = "ask", True
        st.understood = "Тайна всё равно откроется раньше срока."
        if has_event(s, "reveal"):
            _say(s, "early.afterReveal")
        elif has_event(s, "accuse"):
            _say(s, "early.afterAccuse")
        elif w.tempered["impulse"]:
            _say(s, "early.tempered")
        elif firm and w.credibility == "shaken":
            _say(s, "early.shaken")
            _set_intent(s, st, "call")
        elif firm:
            _say(s, "early.firm")
            _fire(s, "reveal", "statement", st)
        else:
            _say(s, "early.soft")
            _set_intent(s, st, "call")
    elif part == "mars.quarrel":
        st.data["topic"] = "quarrel"
        st.understood = "На неделе будет ссора из-за неосторожного слова."
        if has_event(s, "accuse"):
            _say(s, "quarrel.afterAccuse")
        elif has_event(s, "reveal"):
            _say(s, "quarrel.afterReveal")
        elif "accuse" in w.intents:
            if firm and not w.tempered["impulse"] and w.credibility == "intact":
                _say(s, "quarrel.intent.firm")
                _fire(s, "accuse", "license", st)
                st.understood = "Раз ссоры не миновать — можно отправлять."
            else:
                _say(s, "quarrel.intent")
            s.mood = "angry"
        else:
            _say(s, "quarrel.trusts" if w.belief == "trusts" else "quarrel.none")
            s.mood = "worried"
    elif part == "mars.rival":
        _dark_said(s, st, LINES["rival.echo"][0])
    elif part == "moon.otherwise":
        # Фраза, под которую подходит любой исход: содержания в ней нет.
        st.data["barnum"] = True
        _hollow_said(s, st, "otherwise")
    elif part == "moon.forget":
        st.data["topic"] = "forget"
        st.understood = "Муж о важном не вспомнит; праздновать придётся самой."
        if has_event(s, "reveal"):
            _say(s, "forget.afterReveal")
            w.credibility = "shaken"
            st.understood = "Гадалка спорит с тем, что муж уже объяснил."
        elif w.expectation == "luxury":
            _say(s, "forget.luxury")
            w.credibility = "shaken"
            st.understood = "Из двух обещаний она выбрала то, что приятнее."
        else:
            _say(s, "forget.resonance" if "date" in s.questions else "forget")
            w.expectation = "low"
            s.mood = "tired"
    elif part == "uranus.stage":
        _stage(s, st, firm)
    elif part == "uranus.stranger":
        _kind_said(s, st, echo=LINES[f"stranger.{tone}"][0], fact="seen", resonance=LINES["stranger.resonance"][0],
                   after_accuse="stranger.afterAccuse", after_reveal="stranger.afterReveal")


