def _key_part(st: Statement) -> str | None:
    return next((part for part in st.parts if part in RECOGNITION), None)


def _reveal_index(s: State) -> int:
    reveal = E.event_of(s, "reveal")
    st = statement_of(s, reveal.statement_id) if reveal else None
    return len(s.statements) if reveal is None or reveal.later or st is None else s.statements.index(st)


def _recognized(s: State) -> Statement | None:
    """Верное предсказание, которое гадалка не забрала назад и которое Людмила услышала."""
    if has_event(s, "accuse"):
        return None
    # Раскрытую заранее тайну угадывать было уже нечего — кроме слов, сказанных до звонка.
    limit = _reveal_index(s) if has_event(s, "reveal") else len(s.statements)
    candidates = [st for index, st in enumerate(s.statements)
                  if st.alive and st.data.get("polarity") == "benign" and not st.data.get("mixed")
                  and not st.data.get("contradicts") and index < limit]
    return (next((st for st in candidates if st.tone == E.FIRM and _key_part(st)), None)
            or next((st for st in candidates if _key_part(st)), None))


