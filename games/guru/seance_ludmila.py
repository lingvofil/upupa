def _can_fire(s: State, event_id: str) -> bool:
    return (not has_event(s, event_id) and not (event_id == "accuse" and has_event(s, "reveal"))
            and not (event_id == "reveal" and has_event(s, "accuse")))


def _scene(s: State, event_id: str, beats: tuple[tuple[str, str, str], ...]) -> None:
    for kind, who, text in beats:
        push(s, kind, who, text, event_id)


