# --- архетипы ---------------------------------------------------------------

@dataclass(frozen=True)
class Archetype:
    key: str
    title: str
    emoji: str
    base_trust: int
    style: str  # honest | overreact | poker — насколько реакции выдают правду
    echo: str  # expose | discount | delight — как он реагирует на свои же слова
    question_trust: int  # сколько доверия стоит уточнение
    question_suspicion: int
    suspicion: Mapping[str, int] | None  # только у скептика: подозрение за метод
    reactions: Mapping[str, tuple[str, ...]]  # warm | cold
    statuses: Mapping[str, tuple[str, ...]]  # up | down | asked
    sign_answer: str
    echo_lines: Mapping[str, str]  # soft | critical
    outcomes: Mapping[str, str]  # hit | partial | miss | exposure
    suspicion_lines: tuple[tuple[int, str], ...] = field(default_factory=tuple)


