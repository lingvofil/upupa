"""Тексты и параметры клиентов салона «Гуру».

Всё здесь — шаблоны: детерминированные и проверяемые тестами. Род у каждого
типа клиента фиксирован, поэтому реплики пишутся сразу в нужном роде. Общие
реплики (``"*"``) — в настоящем времени, оно в русском не различает род.
Игрок для клиентов — «мадам», независимо от пола: это сценический образ.
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class Fact:
    """Скрытый факт о клиенте: как он выдаёт себя и как звучит точное попадание."""

    clue: str
    hit: str


@dataclass(frozen=True)
class Decoy:
    """Конкретное предсказание мимо и ответ клиента на него."""

    guess: str
    retort: str


@dataclass(frozen=True)
class ClientKind:
    key: str
    title: str
    emoji: str
    base_trust: int
    gullibility: float  # множитель роста доверия и шанса выудить зацепку
    budget: int  # базовая цена сеанса при полном доверии, ₽
    patience: int  # сколько приёмов клиент терпит
    names: tuple[str, ...]
    intros: tuple[str, ...]
    facts: tuple[Fact, ...]
    decoys: tuple[Decoy, ...]
    skeptic: bool = False  # копит подозрение и может разоблачить
    hates_vague: bool = False  # общие слова снижают доверие
    amplify: int = 1  # множитель сарафана и потерь репутации


