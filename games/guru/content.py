@dataclass(frozen=True)
class WhoTag:
    key: str
    label: str  # кнопка конструктора
    phrase: str  # в предсказании: «… {phrase} изменит»
    card: str  # карта Таро
    button: str  # кнопка толкования
    voice: str  # что мадам говорит вслух


@dataclass(frozen=True)
class WhatTag:
    key: str
    label: str
    sphere: str
    emotion: str
    third: str  # «… коллега изменит»
    second: str  # «… вы сами измените»


@dataclass(frozen=True)
class WhenTag:
    key: str
    label: str
    phrase: str  # «Мне кажется, {phrase} …»
    lead: str  # начало развязки: «В пятницу …»
